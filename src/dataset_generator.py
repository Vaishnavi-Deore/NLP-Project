def generate_dataset(output_path="data/aqi_health_queries.csv", target_per_class=140):
    """
    Generate at least 1,200 unique queries across the 9 classes.
    """
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    records = []

    # Map category to its template list
    category_templates = {
        "AQI Information": AQI_INFO_TEMPLATES,
        "Health Effects": HEALTH_EFFECTS_TEMPLATES,
        "Symptoms": SYMPTOMS_TEMPLATES,
        "Precautions": PRECAUTIONS_TEMPLATES,
        "Masks and Protection": MASKS_TEMPLATES,
        "Outdoor Activities": OUTDOOR_ACTIVITIES_TEMPLATES,
        "Vulnerable Groups": VULNERABLE_GROUPS_TEMPLATES,
        "Respiratory Health": RESPIRATORY_HEALTH_TEMPLATES,
        "Pollution Exposure": POLLUTION_EXPOSURE_TEMPLATES,
    }

    for cat in CATEGORIES:
        seen_queries = set()
        
        # 1. Add extra curated diverse queries
        if cat in EXTRA_DIVERSE_QUERIES:
            for q in EXTRA_DIVERSE_QUERIES[cat]:
                q_clean = q.strip()
                if q_clean not in seen_queries:
                    seen_queries.add(q_clean)
                    records.append({"query": q_clean, "category": cat})

        # 2. Add template-based queries with permutations
        templates = category_templates.get(cat, [])
        for tmpl in templates:
            # Check what placeholders exist in template
            if "{aqi}" in tmpl and "{band}" in tmpl:
                for aqi in random.sample(AQI_VALUES, min(6, len(AQI_VALUES))):
                    for band in random.sample(BANDS, min(3, len(BANDS))):
                        q = tmpl.format(aqi=aqi, band=band)
                        if q not in seen_queries:
                            seen_queries.add(q)
                            records.append({"query": q, "category": cat})
            elif "{aqi}" in tmpl:
                for aqi in random.sample(AQI_VALUES, min(8, len(AQI_VALUES))):
                    q = tmpl.format(aqi=aqi)
                    if q not in seen_queries:
                        seen_queries.add(q)
                        records.append({"query": q, "category": cat})
            elif "{band}" in tmpl:
                for band in BANDS:
                    q = tmpl.format(band=band)
                    if q not in seen_queries:
                        seen_queries.add(q)
                        records.append({"query": q, "category": cat})
            elif "{color}" in tmpl:
                for color in COLORS:
                    q = tmpl.format(color=color)
                    if q not in seen_queries:
                        seen_queries.add(q)
                        records.append({"query": q, "category": cat})
            else:
                q = tmpl.strip()
                if q not in seen_queries:
                    seen_queries.add(q)
                    records.append({"query": q, "category": cat})

        # 3. Add linguistic variants (prefixes / suffixes) if needed to ensure >= target_per_class
        prefixes = [
            "Can you tell me: ",
            "I want to know, ",
            "Please explain: ",
            "Quick question: ",
            "Doctor, ",
            "Hey AQI-Sense, ",
            "Is it true that ",
            "Could you explain if ",
        ]
        
        while len(seen_queries) < target_per_class:
            base_q = random.choice(list(seen_queries))
            # Remove existing punctuation at end
            base_q_core = base_q.rstrip("?.,!")
            prefix = random.choice(prefixes)
            # Make first letter lower if lowercase prefix
            if prefix.endswith("that ") or prefix.endswith("if "):
                new_q = f"{prefix}{base_q_core[0].lower() + base_q_core[1:]}?"
            else:
                new_q = f"{prefix}{base_q_core}?"
            
            if new_q not in seen_queries:
                seen_queries.add(new_q)
                records.append({"query": new_q, "category": cat})

    df = pd.DataFrame(records)
    # Shuffle dataset
    df = df.sample(frac=1.0, random_state=42).reset_index(drop=True)
    df.to_csv(output_path, index=False, encoding="utf-8")
    
    print(f"Dataset generated successfully at: {output_path}")
    print(f"Total rows: {len(df)}")
    print("\nClass distribution:")
    print(df["category"].value_counts())
    return df

if __name__ == "__main__":
    generate_dataset()
